package signal

import "testing"

// Golden values were generated with the OregonDSP 1.3.1 JavaScript artifact
// used by SeisPlotJS.

func TestOregonCenteredHilbertExactGolden(t *testing.T) {
	filter, err := NewCenteredHilbertTransform(10, 0.05, 0.95)
	if err != nil {
		t.Fatal(err)
	}
	wantCoefficients := []float64{
		1.1187021309311262e-9, -0.0960223451256752, 1.3782458729849623e-8,
		-0.07441437989473343, -1.526658266470804e-8, -0.11460818350315094,
		3.654209157488708e-10, -0.20432430505752563, 1.79707648761962e-9,
		-0.633985698223114, -1.79707648761962e-9, 0.633985698223114,
		-1.79707648761962e-9, 0.20432430505752563, 1.79707648761962e-9,
		0.11460818350315094, 3.654209157488708e-10, 0.07441437989473343,
		-1.526658266470804e-8, 0.0960223451256752, 1.4901161193847656e-8,
	}
	assertFloatSliceClose(t, "OregonDSP centered Hilbert coefficients", filter.Coefficients(), wantCoefficients, 0)

	got := filter.Filter([]float64{1, -0.5, 0.25, 2, -1, 0.125})
	want := []float64{
		3.3527612686157227e-8, -0.09602231532335281, 0.04801115393638611,
		-0.09841998666524887, -0.1548374742269516, -0.037189461290836334,
		-0.1035274788737297, -0.15856198966503143, -0.13635599613189697,
		-0.5704585313796997, -0.10598179697990417, 0.6798135638237,
		-1.6105046272277832, 0.9968063235282898, 1.0865609645843506,
		-0.46829643845558167, 0.43059268593788147, -0.10125782340765,
		0.21754968166351318, 0.00001774482734617777, 0.11514367163181305,
		-0.05040889233350754, 0.2013464719057083, -0.09602225571870804,
		0.012002721428871155, 3.725290298461914e-9,
	}
	assertFloatSliceClose(t, "OregonDSP centered Hilbert convolution", got, want, 2e-6)
	for index, value := range got {
		if value != float64(float32(value)) {
			t.Fatalf("centered Hilbert output[%d] was not rounded to Float32: %.17g", index, value)
		}
	}
}
